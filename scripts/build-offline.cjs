const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');
const root = path.resolve(__dirname, '..');
const files = ['index.html','refresh.css','app.js','offline.js','state-paths.js','states-data.js','state-images.js','facts.js','achievements.js',
  ...fs.readdirSync(path.join(root,'images')).filter(name=>name.endsWith('.jpg')).sort().map(name=>'images/'+name)];
const hash = createHash('sha256');
for (const file of files) hash.update(fs.readFileSync(path.join(root,file)));
const version = hash.digest('hex').slice(0,12);
const worker = `// Generated by npm run build:offline; commit with every game change.
const CACHE = 'plate-tracker-${version}';
const FILES = ${JSON.stringify(files,null,2)};
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES)));
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith('plate-tracker-') && key !== CACHE) await caches.delete(key);
    }
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin) return;
  const root = new URL('./', self.location.href);
  const relative = url.pathname.slice(root.pathname.length);
  const isHome = url.pathname === root.pathname || relative === 'index.html';
  if (!url.pathname.startsWith(root.pathname) || (!isHome && !FILES.includes(relative))) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    return (await cache.match(new URL(isHome ? 'index.html' : relative, root).href)) || fetch(event.request);
  })());
});
`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(path.join(root,'sw.js'),'utf8') !== worker) {
    console.error('Offline cache is stale. Run npm run build:offline.');
    process.exitCode=1;
  }
} else fs.writeFileSync(path.join(root,'sw.js'), worker);
